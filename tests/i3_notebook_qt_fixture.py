"""Render real Qt controls so CI checks the displayed palette, not config alone."""
import importlib
import sys

major = int(sys.argv[1])
Widgets = importlib.import_module(f"PyQt{major}.QtWidgets")
Gui = importlib.import_module(f"PyQt{major}.QtGui")
Core = importlib.import_module(f"PyQt{major}.QtCore")
app = Widgets.QApplication(["notebook-qt-swatches"])
window = Widgets.QWidget()
window.setWindowTitle(f"Notebook Qt{major} swatches")
window.resize(460, 360)
layout = Widgets.QVBoxLayout(window)
tabs = Widgets.QTabWidget()
tabs.addTab(Widgets.QLabel("Primeira página"), "Aba ativa")
tabs.addTab(Widgets.QLabel("Segunda página"), "Outra aba")
layout.addWidget(tabs)
progress = Widgets.QProgressBar()
progress.setValue(65)
layout.addWidget(progress)
orientation = Core.Qt.Orientation.Horizontal if major == 6 else Core.Qt.Horizontal
scale = Widgets.QSlider(orientation)
scale.setValue(65)
layout.addWidget(scale)
checked = Widgets.QCheckBox("Marcado")
checked.setChecked(True)
layout.addWidget(checked)
radio = Widgets.QRadioButton("Rádio")
radio.setChecked(True)
layout.addWidget(radio)
items = Widgets.QListWidget()
item = Widgets.QListWidgetItem(Gui.QIcon.fromTheme("folder"), "Pasta selecionada")
items.addItem(item)
items.setCurrentRow(0)
layout.addWidget(items)
button = Widgets.QPushButton("Ação padrão")
button.setDefault(True)
layout.addWidget(button)
window.show()
window.activateWindow()
window.raise_()
items.setFocus()
print(f"style={app.style().objectName()} font={app.font().family()} {app.font().pointSize()} icons={Gui.QIcon.themeName()}", flush=True)
sys.exit(app.exec() if major == 6 else app.exec_())
