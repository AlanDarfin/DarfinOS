#!/usr/bin/env python3
"""Notebook-only Flatpak launchers and portable theme assets.

No persistent Flatpak overrides and no changes to an application's config home.
The host's Qt style libraries are deliberately not injected into a runtime.
"""
from __future__ import annotations

import fcntl
import json
import os
from pathlib import Path
import re
import shlex
import shutil
import subprocess
import sys
import tempfile

HOME = Path.home()
PROFILE = HOME / ".config/darfinos/i3-notebook"
DATA = PROFILE / "flatpak/share"
SYSTEM_ICONS = Path("/usr/share/icons")
SYSTEM_EXPORTS = Path("/var/lib/flatpak/exports/share/applications")
GENERATED = "# Generated by DarfinOS i3 Notebook; original Flatpak export is unchanged.\n"
CACHE_VERSION = 1
RUN_EXEC = re.compile(r'^(?:"(?:/usr/bin/)?flatpak"|(?:/usr/bin/)?flatpak)(?=\s+run(?:\s|$))')
THEME_NAME = re.compile(r"[A-Za-z0-9][A-Za-z0-9 ._+-]*\Z")


def data_home():
    return Path(os.environ.get("XDG_DATA_HOME") or HOME / ".local/share")


def cursor_choice():
    try:
        from desktop import cursor_preference
        preference = cursor_preference()
        if preference:
            return preference[0], preference[1], preference[2].parent.parent
    except (ImportError, OSError, ValueError):
        pass
    return "Bibata-Modern-Ice", 24, None


def find_theme(name):
    for root in (HOME / ".icons", data_home() / "icons", SYSTEM_ICONS):
        directory = root / name
        if (directory / "index.theme").is_file():
            return directory.resolve()
    return None


def theme_sources(cursor):
    sources = {}
    # Papirus Yellow inherits both parent themes. Include them so aliases to
    # /usr/share/icons on the host resolve to files inside the runtime too.
    for name in ("Papirus-Yellow", "Papirus-Dark", "Papirus"):
        if directory := find_theme(name):
            sources[name] = directory
    name, _, directory = cursor
    if directory and THEME_NAME.fullmatch(name) and (directory / "index.theme").is_file():
        sources[name] = directory.resolve()
    return sources


def source_stamp(sources):
    values = {"version": CACHE_VERSION, "themes": {}}
    for name, directory in sources.items():
        # Package upgrades replace index.theme; the Yellow installer replaces
        # its directory. Both changes invalidate this inexpensive stamp.
        stat = (directory / "index.theme").stat()
        root = directory.stat()
        values["themes"][name] = [str(directory), stat.st_size, stat.st_mtime_ns, root.st_mtime_ns]
    return values


def copy_portable_theme(source, destination, all_sources, stage):
    shutil.copytree(source, destination, symlinks=True)
    # Preserve aliases but translate absolute host links into local links.
    # Never make unrelated host files reachable through a cursor/icon alias.
    links = []
    for folder, directories, files in os.walk(destination, followlinks=False):
        links.extend(Path(folder) / name for name in directories + files if (Path(folder) / name).is_symlink())
    for link in links:
        original = source / link.relative_to(destination)
        try:
            target = original.resolve(strict=True)
        except (OSError, RuntimeError):
            link.unlink()
            continue
        replacement = None
        for theme_name, root in sorted(all_sources.items(), key=lambda item: len(str(item[1])), reverse=True):
            if target.is_relative_to(root):
                replacement = stage / theme_name / target.relative_to(root)
                break
        link.unlink()
        if replacement is not None:
            link.symlink_to(os.path.relpath(replacement, start=link.parent))


def refresh_assets(cursor=None):
    cursor = cursor or cursor_choice()
    sources = theme_sources(cursor)
    DATA.mkdir(parents=True, exist_ok=True)
    with (DATA.parent / ".assets.lock").open("a") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        stamp = source_stamp(sources)
        manifest = DATA / "assets.json"
        try:
            if json.loads(manifest.read_text()) == stamp and (DATA / "icons").is_dir():
                return sources
        except (OSError, ValueError):
            pass
        with tempfile.TemporaryDirectory(dir=DATA, prefix=".icons-") as folder:
            stage = Path(folder) / "icons"
            stage.mkdir()
            for name, source in sources.items():
                copy_portable_theme(source, stage / name, sources, stage)
            old = Path(folder) / "previous"
            if (DATA / "icons").exists():
                (DATA / "icons").rename(old)
            try:
                stage.rename(DATA / "icons")
            except OSError:
                if old.exists():
                    old.rename(DATA / "icons")
                raise
        temporary = DATA / ".assets.json.new"
        temporary.write_text(json.dumps(stamp, sort_keys=True) + "\n")
        temporary.replace(manifest)
    return sources


def refresh_cursor_settings(cursor):
    name, size, _ = cursor
    if not THEME_NAME.fullmatch(name) or not 8 <= size <= 128:
        raise ValueError("Preferência de cursor inválida.")
    directory = DATA.parent / "config"
    settings = ("[Settings]\ngtk-theme-name=DarfinOS-Notebook\n"
                "gtk-icon-theme-name=Papirus-Yellow\ngtk-font-name=DejaVu Sans 10\n"
                f"gtk-cursor-theme-name={name}\ngtk-cursor-theme-size={size}\n"
                "gtk-application-prefer-dark-theme=true\ngtk-xft-antialias=1\n"
                "gtk-xft-hinting=1\ngtk-xft-hintstyle=hintslight\n")
    for version in ("gtk-3.0", "gtk-4.0"):
        target = directory / version / "settings.ini"
        target.parent.mkdir(parents=True, exist_ok=True)
        if not target.exists() or target.read_text() != settings:
            with tempfile.NamedTemporaryFile("w", dir=target.parent, delete=False) as staged:
                staged.write(settings)
            Path(staged.name).replace(target)
    return directory


def desktop_quote(value):
    # Desktop Entry Exec escaping, not shell quoting. Percent is a field code.
    escaped = value.replace("\\", "\\\\").replace('"', '\\"').replace("`", "\\`").replace("$", "\\$").replace("%", "%%")
    return '"' + escaped + '"'


def wrap_desktop(text):
    lines = []
    changed = False
    helper = f'{desktop_quote("/usr/bin/python3")} {desktop_quote(str(PROFILE / "flatpak.py"))}'
    for line in text.splitlines(keepends=True):
        if line.startswith("Exec="):
            command = line[5:]
            replaced, count = RUN_EXEC.subn(lambda _: helper, command, count=1)
            changed |= bool(count)
            line = "Exec=" + replaced
        elif line.strip() == "DBusActivatable=true":
            # D-Bus activation would bypass our launch-scoped environment.
            line = "DBusActivatable=false\n"
        lines.append(line)
    return GENERATED + "".join(lines) if changed else None


def refresh_launchers():
    applications = DATA / "applications"
    applications.mkdir(parents=True, exist_ok=True)
    exports = (SYSTEM_EXPORTS, data_home() / "flatpak/exports/share/applications")
    available = {}
    for directory in exports:
        for path in sorted(directory.glob("*.desktop")):
            try:
                wrapped = wrap_desktop(path.read_text(encoding="utf-8"))
            except (OSError, UnicodeError):
                continue
            if wrapped is not None:
                available[path.name] = wrapped
    # Respect personal desktop customizations (including the Vivaldi keyring
    # flags installed by DarfinOS). Only clone IDs already exported by Flatpak.
    for name in list(available):
        personal = data_home() / "applications" / name
        if personal.is_file():
            try:
                wrapped = wrap_desktop(personal.read_text(encoding="utf-8"))
            except (OSError, UnicodeError):
                continue
            if wrapped is None:
                # The user replaced this app with a native command. Do not
                # shadow it with an old system Flatpak export.
                del available[name]
            else:
                available[name] = wrapped
    for name, content in available.items():
        target = applications / name
        if target.exists() and not target.read_text(encoding="utf-8").startswith(GENERATED):
            continue
        if target.is_symlink():
            continue
        if not target.exists() or target.read_text(encoding="utf-8") != content:
            with tempfile.NamedTemporaryFile("w", dir=applications, delete=False, encoding="utf-8") as staged:
                staged.write(content)
            Path(staged.name).replace(target)
    for target in applications.glob("*.desktop"):
        if target.name not in available and not target.is_symlink() and target.read_text(encoding="utf-8").startswith(GENERATED):
            target.unlink()
    return len(available)


def app_id(arguments):
    # Flatpak exports use --key=value. Also accept ordinary CLI option/value
    # pairs without interpreting application arguments after the app ID.
    value_options = {"--arch", "--branch", "--command", "--cwd", "--commit", "--runtime",
                     "--runtime-version", "--runtime-commit", "--installation", "--env",
                     "--unset-env", "--filesystem", "--nofilesystem", "--socket", "--nosocket",
                     "--device", "--nodevice", "--allow", "--disallow", "--persist",
                     "--talk-name", "--own-name", "--system-talk-name", "--system-own-name"}
    skip = False
    for value in arguments[1:]:
        if skip:
            skip = False
        elif value in value_options:
            skip = True
        elif value == "--":
            continue
        elif not value.startswith("-"):
            return value
    return None


def run_context(arguments):
    context = {"options": [], "branch": None}
    selectors = {"--arch", "--installation"}
    values = {"--branch", "--command", "--cwd", "--commit", "--runtime", "--runtime-version",
              "--runtime-commit", "--env", "--unset-env", "--filesystem", "--nofilesystem",
              "--socket", "--nosocket", "--device", "--nodevice", "--allow", "--disallow",
              "--persist", "--talk-name", "--own-name", "--system-talk-name", "--system-own-name"}
    index = 1
    while index < len(arguments):
        value = arguments[index]
        key, equals, inline = value.partition("=")
        if not value.startswith("-"):
            break
        if key in selectors or key in values:
            supplied = inline if equals else (arguments[index + 1] if index + 1 < len(arguments) else "")
            if key in selectors:
                context["options"].append(key + "=" + supplied)
            elif key == "--branch":
                context["branch"] = supplied
            if not equals:
                index += 1
        elif value in ("--user", "--system"):
            context["options"].append(value)
        index += 1
    return context


def app_runtime(executable, application, context=None):
    if not application:
        return ""
    context = context or {"options": [], "branch": None}
    command = [executable, "info", "--show-runtime", *context["options"], application]
    if context["branch"]:
        command.append(context["branch"])
    result = subprocess.run(command, text=True, capture_output=True, timeout=8, check=False)
    return result.stdout.strip() if result.returncode == 0 else ""


def qt_style(executable, application, context=None):
    context = context or {"options": [], "branch": None}
    try:
        runtime = app_runtime(executable, application, context)
    except (OSError, subprocess.TimeoutExpired):
        return "Fusion", ""
    parts = runtime.split("/")
    if len(parts) != 3 or parts[0] != "org.kde.Platform":
        return "Fusion", runtime
    reference = f"org.kde.KStyle.Kvantum/{parts[1]}/{parts[2]}"
    try:
        extension = subprocess.run([executable, "info", "--show-location", *context["options"], reference], text=True,
                                   capture_output=True, timeout=8, check=False)
    except (OSError, subprocess.TimeoutExpired):
        return "Fusion", runtime
    if extension.returncode == 0:
        location = Path(extension.stdout.strip()) / "files"
        if location.is_dir() and any(location.rglob("libkvantum.so")):
            return "kvantum", runtime
    return "Fusion", runtime


def install_qt_style(application):
    executable = shutil.which("flatpak")
    if not executable:
        raise ValueError("Flatpak não está instalado.")
    runtime = app_runtime(executable, application)
    parts = runtime.split("/")
    if len(parts) != 3 or parts[0] != "org.kde.Platform":
        raise ValueError("Este aplicativo não usa o runtime KDE. Nenhuma extensão foi instalada.")
    return subprocess.run([executable, "install", "--user", "--arch=" + parts[1], "flathub",
                           "org.kde.KStyle.Kvantum//" + parts[2]], check=False).returncode


def sandbox_arguments(cursor, style="Fusion"):

    name, size, _ = cursor
    arguments = []
    theme = HOME / ".themes/DarfinOS-Notebook"
    appearance = PROFILE / "appearance"
    config = DATA.parent / "config"
    for directory in (theme, DATA, config, appearance, HOME / ".fonts", data_home() / "fonts"):
        if directory.is_dir():
            arguments.append(f"--filesystem={directory}:ro")
    environment = {
        "GTK_THEME": "DarfinOS-Notebook",
        "GTK2_RC_FILES": str(theme / "gtk-2.0/gtkrc"),
        "XCURSOR_THEME": name,
        "XCURSOR_SIZE": str(size),
        "XCURSOR_PATH": f"{DATA / 'icons'}:/usr/share/icons",
        "XDG_DATA_DIRS": f"{DATA}:{appearance / 'share'}:/app/share:/usr/share",
        "XDG_CONFIG_DIRS": f"{config}:{appearance}:/etc/xdg",
        # Fusion ships with Qt itself; a host Kvantum library cannot be loaded
        # by an unrelated Flatpak ABI. KDE runtime platform themes can still
        # use the scoped kdeglobals palette and font/icon preferences.
        "QT_STYLE_OVERRIDE": style,
    }
    arguments += [f"--env={key}={value}" for key, value in environment.items()]
    return arguments


def launch(arguments):
    executable = shutil.which("flatpak")
    if not executable:
        raise ValueError("Flatpak não está instalado.")
    if not arguments or arguments[0] != "run" or len(arguments) == 1:
        raise ValueError("Uso: flatpak.py run [opções do Flatpak] APP_ID [argumentos]")
    cursor = cursor_choice()
    refresh_assets(cursor)
    refresh_cursor_settings(cursor)
    environment = os.environ.copy()
    # Do not leak host Qt plugin selection or toolkit config homes to a runtime.
    for key in ("QT_QPA_PLATFORMTHEME", "QT_PLUGIN_PATH", "QT_QPA_PLATFORM_PLUGIN_PATH", "GTK_PATH"):
        environment.pop(key, None)
    style, _ = qt_style(executable, app_id(arguments), run_context(arguments))
    os.execve(executable, [executable, "run", *sandbox_arguments(cursor, style), *arguments[1:]], environment)


def dispatch(arguments):
    if not arguments:
        raise ValueError("Nenhum comando para iniciar.")
    if len(arguments) >= 2 and arguments[0] in ("flatpak", "/usr/bin/flatpak") and arguments[1] == "run":
        return launch(arguments[1:])
    # Rofi already expands Desktop Entry field codes. Keep those exact argv
    # boundaries and never evaluate a desktop command as shell source.
    os.execvpe(arguments[0], arguments, os.environ.copy())


def launch_desktop(identifier, arguments):
    if not re.fullmatch(r"[A-Za-z0-9_.-]+\.desktop", identifier):
        raise ValueError("Identificador de aplicativo inválido.")
    refresh_launchers()
    cached = DATA / "applications" / identifier
    if not cached.is_file():
        executable = shutil.which("gtk-launch")
        if not executable:
            raise ValueError("gtk-launch não está instalado.")
        os.execvpe(executable, [executable, "--", identifier, *arguments], os.environ.copy())
        return
    try:
        import gi
        gi.require_version("Gio", "2.0")
        from gi.repository import Gio
        application = Gio.DesktopAppInfo.new_from_filename(str(cached))
        if application is None:
            raise ValueError("O lançador Flatpak não pôde ser lido.")
        files = [Gio.File.new_for_commandline_arg(value) for value in arguments]
        if not application.launch(files, None):
            raise ValueError("Não foi possível iniciar o aplicativo Flatpak.")
    except ImportError as error:
        raise ValueError("Instale python-gobject pelas dependências do i3 Notebook.") from error


def main(arguments=None):
    arguments = sys.argv[1:] if arguments is None else arguments
    try:
        if arguments == ["rofi-command"]:
            print(shlex.join(["/usr/bin/python3", str(PROFILE / "flatpak.py"), "dispatch"]) + " {cmd}")
            return 0
        if arguments and arguments[0] == "dispatch":
            dispatch(arguments[1:])
            return 0
        if len(arguments) >= 2 and arguments[0] == "desktop":
            launch_desktop(arguments[1], arguments[2:])
            return 0
        if len(arguments) == 2 and arguments[0] == "install-qt-style":
            return install_qt_style(arguments[1])
        if len(arguments) == 2 and arguments[0] == "inspect":
            executable = shutil.which("flatpak")
            if not executable:
                raise ValueError("Flatpak não está instalado.")
            style, runtime = qt_style(executable, arguments[1])
            print(json.dumps({"application": arguments[1], "runtime": runtime, "qt_style": style,
                              "qt_palette": "Notebook via runtime platform theme; app overrides may take precedence",
                              "persistent_overrides": False}))
        elif arguments == ["refresh"]:
            cursor = cursor_choice()
            themes = refresh_assets(cursor)
            refresh_cursor_settings(cursor)
            launchers = refresh_launchers()
            print(json.dumps({"themes": sorted(themes), "launchers": launchers}))
        else:
            launch(arguments)
        return 0
    except (OSError, ValueError, subprocess.TimeoutExpired) as error:
        print(f"DarfinOS · Flatpak: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
